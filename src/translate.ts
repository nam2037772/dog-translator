function detectMoods(text: string): Mood[] {
  const found: Mood[] = []
  for (const mood of Object.keys(MOOD_KEYWORDS) as Mood[]) {
    if (MOOD_KEYWORDS[mood].some((kw) => text.includes(kw))) {
      found.push(mood)
    }
  }
  return found
}

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]
}

export function translate(input: string, character: CharacterId): string {
  const text = input.trim()
  const bank = RESPONSES[character]
  if (!text) return pick(bank.default)

  const moods = detectMoods(text)
  if (moods.length === 0) return pick(bank.default)

  // 감지된 감정 중 하나를 무작위로 골라 다양성 확보
  const mood = pick(moods)
  return pick(bank[mood])
}
